// TALERA Free staging build: extract only identical anonymous app code into
// fingerprinted Cloudflare Workers Static Assets. No user data is read or cached.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import existingWorker from '../src/timeline-polish-worker.js';

const ROOT = resolve('.');
const OUTPUT = resolve(ROOT, 'dist/free-scale-assets');
const GENERATED = resolve(ROOT, 'src/generated/free-scale-shell.mjs');
const REPORT = resolve(ROOT, 'dist/free-scale-test-manifest.json');
const SOURCE = 'https://talera-free-build.invalid/';
const PREFIX = '/_talera_free_static/';
const response = await existingWorker.fetch(new Request(SOURCE), {}, {});
assert.equal(response.status, 200, 'Anonymous build shell must be available');
assert.match(response.headers.get('content-type') || '', /^text\/html/i);
const original = await response.text();
assert.ok(original.length > 100000, 'Refuse to build from an incomplete app shell');
const entries = [];
const assets = new Map();
const regex = /<(script|style)\b([^>]*)>([\s\S]*?)<\/\1\s*>/gi;
const out = original.replace(regex, (tag, kind, attributes, body) => {
  const isScript = kind.toLowerCase() === 'script';
  if (body.trim().length < 48) return tag;
  if (/\b(?:nonce|integrity|src|scoped)\s*=/i.test(attributes)) return tag;
  if (isScript) {
    const type = (attributes.match(/\btype\s*=\s*["']([^"']+)["']/i) || [,'text/javascript'])[1].toLowerCase();
    if (!['text/javascript', 'application/javascript'].includes(type)) return tag;
    if (/\b(?:document\.write|document\.currentScript|import\.meta)\b/i.test(body)) return tag;
  } else if (/url\s*\(/i.test(body)) {
    // Moving relative CSS url() references changes their base; preserve those styles.
    return tag;
  }
  const ext = isScript ? '.js' : '.css';
  const digest = createHash('sha256').update(body).digest('hex');
  const asset = PREFIX + digest + ext;
  if (!assets.has(asset)) assets.set(asset, body);
  const replacement = isScript
    ? '<script' + attributes + ' src="' + asset + '"></script>'
    : '<link' + attributes + ' rel="stylesheet" href="' + asset + '">';
  entries.push({kind, asset, digest, bytes: Buffer.byteLength(body), originalTag: tag, replacementTag: replacement});
  return replacement;
});
assert.ok(entries.some(e => e.kind === 'script'), 'At least one JavaScript block must move');
assert.ok(entries.some(e => e.kind === 'style'), 'At least one CSS block must move');
assert.ok(Buffer.byteLength(out) < Buffer.byteLength(original), 'Optimized shell must be smaller');

await rm(OUTPUT, {recursive:true, force:true});
await mkdir(OUTPUT, {recursive:true});
for (const [path, content] of assets) {
  const destination = resolve(OUTPUT, '.' + path);
  assert.ok(destination.startsWith(OUTPUT + '/'), 'Asset path must remain under staging output');
  await mkdir(dirname(destination), {recursive:true});
  await writeFile(destination, content);
}
await writeFile(resolve(OUTPUT, '_headers'),
  '/_talera_free_static/*\n  Cache-Control: public, max-age=31536000, immutable\n  X-Content-Type-Options: nosniff\n');
await mkdir(dirname(GENERATED), {recursive:true});
await writeFile(GENERATED,
  '// Generated by scripts/build-free-scale.mjs; do not edit by hand.\n' +
  'export const anonymousFreeShell = ' + JSON.stringify(out) + ';\n' +
  'export const shellBuildStats = ' + JSON.stringify({
    originalBytes:Buffer.byteLength(original),
    shellBytes:Buffer.byteLength(out),
    extractedAssets:assets.size,
    scriptBlocks:entries.filter(e=>e.kind==='script').length,
    styleBlocks:entries.filter(e=>e.kind==='style').length
  }) + ';\n'
);
await mkdir(dirname(REPORT), {recursive:true});
await writeFile(REPORT, JSON.stringify({
  source: SOURCE,
  originalBytes:Buffer.byteLength(original),
  shellBytes:Buffer.byteLength(out),
  extractedAssets: assets.size,
  entries
}, null, 2));
console.log('TALERA_FREE_STAGE_BUILD', JSON.stringify({
  anonymousHtmlBytesBefore:Buffer.byteLength(original),
  anonymousHtmlBytesAfter:Buffer.byteLength(out),
  immutableAssetCount:assets.size,
  extractedCodeBytes:[...assets.values()].reduce((n,v)=>n+Buffer.byteLength(v),0)
}));